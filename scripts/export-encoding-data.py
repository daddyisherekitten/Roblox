"""Generate decoder facts from WHATWG; cached sources make --check reproducible."""
import argparse
import hashlib
import json
from pathlib import Path
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / 'src/HTMLEngine/Encoding/Data.luau'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    sources = {}
    for name in ('encodings', 'indexes'):
        cache = ROOT / f'build/reference/encoding-{name}.json'
        url = f'https://encoding.spec.whatwg.org/{name}.json'
        if not cache.exists():
            cache.parent.mkdir(parents=True, exist_ok=True)
            with urlopen(url, timeout=60) as response:
                cache.write_bytes(response.read())
        raw = cache.read_bytes()
        sources[name] = json.loads(raw)
        sources[name + '-hash'] = hashlib.sha256(raw).hexdigest()
    aliases, names, single = {}, {}, set()
    for group in sources['encodings']:
        for encoding in group['encodings']:
            name = encoding['name'].lower()
            names[name] = encoding['name']
            for label in encoding['labels']:
                aliases[label] = name
            if group['heading'] == 'Legacy single-byte encodings':
                single.add(name)
    rows = ['--!strict', '-- Generated by scripts/export-encoding-data.py; factual WHATWG tables.',
            '-- https://encoding.spec.whatwg.org/encodings.json SHA256 ' + sources['encodings-hash'],
            '-- https://encoding.spec.whatwg.org/indexes.json SHA256 ' + sources['indexes-hash'],
            'local data={Labels={']
    rows += [f'\t["{label}"]="{name}",' for label, name in sorted(aliases.items())]
    rows.append('},Names={')
    rows += [f'\t["{name}"]="{display}",' for name, display in sorted(names.items())]
    rows.append('},SingleByte={')
    for name in sorted(single):
        if name == 'iso-8859-8-i':
            continue
        index = sources['indexes'][name]
        assert len(index) == 128
        rows.append(f'\t["{name}"]={{' + ','.join(str(cp) if cp is not None else 'false' for cp in index) + '},')
    rows += ['}}', 'data.SingleByte["iso-8859-8-i"]=data.SingleByte["iso-8859-8"]', 'return data', '']
    source = '\n'.join(rows)
    outputs = {OUTPUT: source}
    for name, module in [('gb18030','GB18030'), ('gb18030-ranges','GBRanges'),
                         ('big5','Big5'), ('jis0208','JIS0208'), ('jis0212','JIS0212'), ('euc-kr','EUCKR')]:
        index = sources['indexes'][name]
        rows = ['--!strict', '-- Generated WHATWG index ' + name + '; SHA256 ' + sources['indexes-hash'], 'return {']
        values = ['{' + str(row[0]) + ',' + str(row[1]) + '}' if isinstance(row,list)
                  else str(row) if row is not None else 'false' for row in index]
        rows += ['\t' + ','.join(values[i:i+128]) + ',' for i in range(0,len(values),128)]
        rows += ['}', '']
        outputs[OUTPUT.parent / 'Indexes' / (module + '.luau')] = '\n'.join(rows)
    for target, source in outputs.items():
        if args.check:
            if target.read_text(encoding='utf-8') != source:
                raise SystemExit(str(target.relative_to(ROOT)) + ' differs from the reference export')
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(source, encoding='utf-8')
    print(f'Encoding facts: {len(aliases)} labels, {len(single)} single-byte and 6 multibyte/range indexes.')


if __name__ == '__main__':
    main()
