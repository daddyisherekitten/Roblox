// Cold rendering dependencies, in dependency order. Each require gets its own
// cooperative checkpoint; no source reflection is needed in published games.
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..','src','HTMLEngine');
const target=path.join(root,'Rendering','LoadingModules.luau');
const visited=new Set(),visiting=new Set(),ordered=[];
function visit(id){
 if(visited.has(id))return;
 assert.ok(!visiting.has(id),`Cold-loading dependency cycle: ${id}`);
 visiting.add(id);
 const base=path.join(root,id),file=fs.existsSync(base+'.luau')?base+'.luau':path.join(base,'init.luau');
 const source=fs.readFileSync(file,'utf8');
 for(const [,chain]of source.matchAll(/require\(script((?:\.[A-Za-z_][A-Za-z_0-9]*)+)\)/g)){
  const parts=id.split('/');
  for(const name of chain.slice(1).split('.'))name==='Parent'?parts.pop():parts.push(name);
  const dependency=parts.join('/');
  if(dependency==='Rendering/LoadingModules')continue;
  // Language dictionaries load only when selected by the element language.
  if(dependency.startsWith('Layout/HyphenationPatterns/')&&dependency!=='Layout/HyphenationPatterns/Characters')continue;
  // Unicode case tables are needed only when a non-identity transform is used.
  if(dependency==='Layout/TextCaseData'||dependency==='Layout/VerticalOrientationData'||dependency==='Layout/TextEmphasisData')continue;
  visit(dependency);
 }
 visiting.delete(id);visited.add(id);ordered.push(id);
}
visit('Rendering/HTMLPage');
const output='--!strict\n-- Generated by scripts/export-loading-modules.cjs. Definitions only; no page work.\nreturn {\n'+ordered.map(id=>'\t"'+id+'",\n').join('')+'}\n';
if(process.argv.includes('--check'))assert.equal(fs.readFileSync(target,'utf8'),output,'Regenerate the cold-loading dependency order');
else fs.writeFileSync(target,output);
console.log(`Cold rendering loader: ${ordered.length} dependencies ${process.argv.includes('--check')?'verified':'saved'}.`);
