"""Export the licensed Source Sans Pro outline font, independently of demo strings.

python -m pip install --target build/python-svg-fonts fonttools==4.65.0
python scripts/export-svg-font.py [--check]
"""
from pathlib import Path
import sys, hashlib, unicodedata, json, subprocess
ROOT=Path(__file__).resolve().parent.parent
sys.path.insert(0,str(ROOT/'build/python-svg-fonts'))
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
face=sys.argv[sys.argv.index('--face')+1] if '--face' in sys.argv else 'Regular'
if face=='Regular':
 for extra in ['Bold','It','BoldIt']:
  subprocess.run([sys.executable,__file__,'--face',extra]+(['--check'] if '--check' in sys.argv else []),check=True)
path=ROOT/'examples/fonts'/('SourceSansPro-'+face+'.ttf')
font=TTFont(path); glyphset=font.getGlyphSet(); order=font.getGlyphOrder(); ids={n:i for i,n in enumerate(order)}
def quoted(s): return json.dumps(s,ensure_ascii=False)
lines=[]
for name in order:
 pen=SVGPathPen(glyphset);glyphset[name].draw(pen)
 lines.append(f'{ids[name]}|{font["hmtx"].metrics[name][0]}|{pen.getCommands()}')
glyphs='--!strict\n-- Generated from '+path.name+'; OFL license in examples/fonts.\nlocal glyphs={}\nlocal data=[====[\n'+'\n'.join(lines)+'\n]====]\nfor line in data:gmatch("[^\\n]+") do local id,advance,path=line:match("^(%d+)|(%d+)|(.*)$");glyphs[tonumber(id)]={Advance=tonumber(advance),Path=path} end\nreturn glyphs\n'
head='--!strict\n-- Generated by scripts/export-svg-font.py; no demo-specific glyph subset.\nlocal font={Family="Source Sans Pro",Weight="400",Style="normal",Units='+str(font['head'].unitsPerEm)+',Ascent='+str(font['hhea'].ascent)+',Descent='+str(font['hhea'].descent)+',XHeight='+str(font['OS/2'].sxHeight)+',SHA256='+quoted(hashlib.sha256(path.read_bytes()).hexdigest())+',Glyphs=require(script.Glyphs),Cmap={},Compose={},Ligatures={},Kern={}}\n'
head+='local cmap=[==['+' '.join(f'{cp}:{ids[name]}' for cp,name in sorted(font.getBestCmap().items()))+']==]\nfor cp,id in cmap:gmatch("(%d+):(%d+)") do font.Cmap[tonumber(cp)]=tonumber(id) end\n'
compose=[]
for cp in font.getBestCmap():
 decomp=unicodedata.normalize('NFD',chr(cp))
 if len(decomp)==2 and ord(decomp[0]) in font.getBestCmap():compose.append(f'{ord(decomp[0])},{ord(decomp[1])},{cp}')
head+='local compose=[==['+' '.join(compose)+']==]\nfor a,b,c in compose:gmatch("(%d+),(%d+),(%d+)") do font.Compose[a..":"..b]=tonumber(c) end\n'
t=font['GSUB'].table
for record in t.FeatureList.FeatureRecord:
 if record.FeatureTag!='liga':continue
 for idx in record.Feature.LookupListIndex:
  for sub in t.LookupList.Lookup[idx].SubTable:
   for first,ligs in sub.ligatures.items():
    for lig in ligs:
     sequence=[ids[first]]+[ids[n] for n in lig.Component]
     head+='table.insert(font.Ligatures,{Glyph='+str(ids[lig.LigGlyph])+',Sequence={'+','.join(map(str,sequence))+'}})\n'
 break
head+='table.sort(font.Ligatures,function(a,b) return #a.Sequence>#b.Sequence end)\n'
t=font['GPOS'].table
for record in t.FeatureList.FeatureRecord:
 if record.FeatureTag!='kern':continue
 for idx in record.Feature.LookupListIndex:
  for sub in t.LookupList.Lookup[idx].SubTable:
   if sub.Format==1:
    entries=[]
    for first,pairs in zip(sub.Coverage.glyphs,sub.PairSet):
     for pair in pairs.PairValueRecord:
      value=getattr(pair.Value1,'XAdvance',0)
      if value:entries.append(f'{ids[first]},{ids[pair.SecondGlyph]},{value}')
    head+='do local rule={Pairs={}};local data=[==['+' '.join(entries)+']==];for a,b,v in data:gmatch("(%d+),(%d+),([%-]?%d+)") do rule.Pairs[a..":"..b]=tonumber(v) end;table.insert(font.Kern,rule) end\n'
   elif sub.Format==2:
    coverage=' '.join(str(ids[n]) for n in sub.Coverage.glyphs)
    c1=' '.join(f'{ids[n]}:{c}' for n,c in sub.ClassDef1.classDefs.items())
    c2=' '.join(f'{ids[n]}:{c}' for n,c in sub.ClassDef2.classDefs.items())
    entries=[]
    for i,row in enumerate(sub.Class1Record):
     for j,cell in enumerate(row.Class2Record):
      value=getattr(cell.Value1,'XAdvance',0)
      if value:entries.append(f'{i},{j},{value}')
    head+='do local rule={Coverage={},Class1={},Class2={},Pairs={}}\n'
    head+='local coverage='+quoted(coverage)+';for id in coverage:gmatch("%d+") do rule.Coverage[tonumber(id)]=true end\n'
    for key,data in [('Class1',c1),('Class2',c2)]:head+='do local data='+quoted(data)+';for id,c in data:gmatch("(%d+):(%d+)") do rule.'+key+'[tonumber(id)]=tonumber(c) end end\n'
    head+='local data=[==['+' '.join(entries)+']==];for a,b,v in data:gmatch("(%d+),(%d+),([%-]?%d+)") do rule.Pairs[a..":"..b]=tonumber(v) end;table.insert(font.Kern,rule) end\n'
 break
head+='font.Weight="'+('700' if 'Bold' in face else '400')+'";font.Style="'+('italic' if 'It' in face else 'normal')+'"\n'
if face=='Regular':head+='font.Faces={Bold=require(script.Bold),It=require(script.It),BoldIt=require(script.BoldIt)}\n'
head+='return font\n' 
for name,content in [('init.luau',head),('Glyphs.luau',glyphs)]:
 out=ROOT/'src/HTMLEngine/SVG/TextFont'
 if face!='Regular':out=out/face
 out=out/name
 if '--check' in sys.argv:assert out.read_text(encoding='utf8')==content,name
 else:out.parent.mkdir(parents=True,exist_ok=True);out.write_text(content,encoding='utf8')
print('SVG font:',len(order),'glyph outlines,',len(font.getBestCmap()),'Unicode mappings; source SHA256',hashlib.sha256(path.read_bytes()).hexdigest())
