"""Freeze permissively licensed TeX hyphenation resources as lazy Luau buckets.

Source licenses/copyright notices remain verbatim in each generated module.
No native text measurements or page-specific word results are shared here.
"""
from pathlib import Path
import argparse
import hashlib
import json
import re
import unicodedata
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
REVISION = "5684c0f51c0b81133db2efbe60a408b4155a3ff5"
BASE = f"https://raw.githubusercontent.com/hyphenation/tex-hyphen/{REVISION}/hyph-utf8/tex/generic/hyph-utf8/patterns/"
# These resources permit redistribution. MIT is selected for dual licensed data.
LANGUAGES = {"en-us": "enUS", "en-gb": "enGB", "de-1996": "de1996",
             "de-1901": "de1901", "de-ch-1901": "deCH1901", "fr": "fr",
             "es": "es", "it": "it", "nl": "nl", "pt": "pt",
             "da": "da", "uk": "uk", "pl": "pl", "sl": "sl",
             "et": "et", "lt": "lt", "af": "af"}


def quoted(value):
    return json.dumps(value, ensure_ascii=False)


def source(url, cache, download):
    if download or not cache.exists():
        cache.parent.mkdir(parents=True, exist_ok=True)
        cache.write_bytes(urllib.request.urlopen(url).read())
    return cache.read_bytes()


def generate(download=False):
    destination = ROOT / "src/HTMLEngine/Layout/HyphenationPatterns"
    destination.mkdir(parents=True, exist_ok=True)
    mappings, counted, manifest = {}, {}, []
    total = 0
    for language, name in LANGUAGES.items():
        cache = ROOT / "scripts/data/hyphenation" / language
        tex = source(BASE + "tex/hyph-" + language + ".tex", cache.with_suffix(".tex"), download)
        patterns = source(BASE + "txt/hyph-" + language + ".pat.txt", cache.with_suffix(".pat.txt"), download)
        try:
            exceptions = source(BASE + "txt/hyph-" + language + ".hyp.txt", cache.with_suffix(".hyp.txt"), download)
        except urllib.error.HTTPError as error:
            if error.code != 404:
                raise
            exceptions = b""
            cache.with_suffix(".hyp.txt").write_bytes(exceptions)
        text = tex.decode("utf-8")
        header = text.split(r"\patterns", 1)[0]
        license_section = header.split("% licence:", 1)[1].split("% hyphenmins:", 1)[0]
        assert ("MIT" in license_section or "BSD" in license_section
                or "Copying and distribution" in license_section), language
        minimum = header.split("% hyphenmins:", 1)[1].split("% texlive:", 1)[0]
        minimum = minimum.split("typesetting:", 1)[-1]
        left = int(re.search(r"left:\s*(\d+)", minimum)[1])
        right = int(re.search(r"right:\s*(\d+)", minimum)[1])
        buckets, alphabet = {}, set()
        for pattern in patterns.decode("utf-8").split():
            letters = re.sub("[0-9]", "", pattern)
            assert not any(char in letters for char in "{}\\%"), (language, pattern)
            weights, at = [0] * (len(letters) + 1), 0
            for char in pattern:
                if char.isascii() and char.isdigit():
                    weights[at] = int(char)
                else:
                    at += 1
            buckets.setdefault(letters[:2], []).append(letters + ":" + "".join(map(str, weights)))
            alphabet.update(letters.replace(".", ""))
        for char in alphabet:
            # One grapheme maps to one pattern letter. Preserve source boundaries.
            for variant in {char, char.upper(), unicodedata.normalize("NFD", char),
                            unicodedata.normalize("NFD", char.upper())}:
                if len(unicodedata.normalize("NFC", variant)) == 1:
                    mappings[variant] = char
            counted[char] = not unicodedata.category(char).startswith(("P", "M"))
        if "ß" in alphabet:
            mappings["ẞ"] = "ß"
        # Keep the complete copyright/license header, including attribution text.
        comments = "\n".join("-- " + line.removeprefix("% ").removeprefix("%") for line in header.splitlines())
        output = ["--!strict", "-- Generated by scripts/generate-hyphenation.py; do not edit.",
                  "-- Source revision " + REVISION, comments,
                  "return table.freeze({", f"Left={left},Right={right},", "Alphabet=table.freeze({"]
        output += [f"[{quoted(char)}]=true," for char in sorted(alphabet)]
        output += ["}),", "Exceptions=table.freeze({"]
        for exception in exceptions.decode("utf-8").split():
            pieces = exception.split("-")
            letters, stops, at = "".join(pieces), [], 0
            for piece in pieces[:-1]:
                at += len(piece)
                stops.append(str(at))
            output.append(f"[{quoted(letters)}]={quoted(','.join(stops))},")
        output += ["}),", "Buckets=table.freeze({"]
        output += [f"[{quoted(key)}]=[==[{chr(10).join(sorted(values))}]==]," for key, values in sorted(buckets.items())]
        output += ["}),", "})", ""]
        (destination / (name + ".luau")).write_text("\n".join(output), encoding="utf-8", newline="\n")
        amount = sum(map(len, buckets.values()))
        total += amount
        manifest.append({"language": language, "module": name, "source": BASE + "tex/hyph-" + language + ".tex",
                         "revision": REVISION, "patterns": amount,
                         "texSHA256": hashlib.sha256(tex).hexdigest(),
                         "patternsSHA256": hashlib.sha256(patterns).hexdigest(),
                         "exceptionsSHA256": hashlib.sha256(exceptions).hexdigest()})
    (ROOT / "scripts/data/hyphenation/manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    output = ["--!strict", "-- Generated Unicode grapheme normalization for the licensed pattern alphabets.",
              "return table.freeze({Mappings=table.freeze({"]
    output += [f"[{quoted(key)}]={quoted(value)}," for key, value in sorted(mappings.items())]
    output += ["}),Counted=table.freeze({"]
    output += [f"[{quoted(key)}]={str(value).lower()}," for key, value in sorted(counted.items())]
    output += ["})})", ""]
    (destination / "Characters.luau").write_text("\n".join(output), encoding="utf-8", newline="\n")
    print(f"Hyphenation: {len(LANGUAGES)} resources, {total} patterns, {len(mappings)} grapheme mappings")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--download", action="store_true", help="Refresh the frozen upstream resources")
    generate(parser.parse_args().download)
