"""Generate CSS Text Decoration3 emphasis eligibility from pinned Unicode17.

This uses the repository's licensed UCD and its decomposition mappings, never
the Python runtime's older/unpinned Unicode tables. Ordinary generation offline.
"""
from pathlib import Path
import hashlib,json
ROOT=Path(__file__).resolve().parent.parent
source=ROOT/'scripts/data/unicode-17.0.0/UnicodeData.txt'
categories=['Cn']*0x110000
decompositions={}
first=None
for line in source.read_text(encoding='utf8').splitlines():
    fields=line.split(';');code=int(fields[0],16);category=fields[2]
    if fields[1].endswith(', First>'):first=code
    elif fields[1].endswith(', Last>'):
        categories[first:code+1]=[category]*(code-first+1);first=None
    else:categories[code]=category
    decomposition=fields[5].split()
    if decomposition:
        decompositions[code]=[int(c,16)for c in decomposition if not c.startswith('<')]
exceptions={0x23,0x25,0x2030,0x2031,0x66a,0x609,0x60a,0x26,0x204a,0x40,0xa7,0xb6,0x204b,0x2053,0x303d}
def eligible_punctuation(code):
    if code in exceptions:return True
    return any(eligible_punctuation(c)for c in decompositions.get(code,[]))
skip=[];separators=[];marks=[]
def ranges(predicate):
    result=[]
    for code,category in enumerate(categories):
        if not predicate(code,category):continue
        if result and result[-1][1]+1==code:result[-1][1]=code
        else:result.append([code,code])
    return result
skip=ranges(lambda c,k:k in {'Cc','Cf','Cn'}or k.startswith('Z')or k.startswith('P')and not eligible_punctuation(c))
separators=ranges(lambda c,k:k.startswith('Z'))
marks=ranges(lambda c,k:k.startswith('M'))
license=(ROOT/'src/HTMLEngine/JavaScript/Unicode.LICENSE.txt').read_text(encoding='utf8')
lines=['--!strict','-- Generated by scripts/generate-text-emphasis.py from pinned Unicode17 UCD.',
       '-- Source SHA256: '+hashlib.sha256(source.read_bytes()).hexdigest(),
       '-- CSS rule: https://www.w3.org/TR/css-text-decor-3/#text-emphasis-style-property',
       *['-- '+line for line in license.splitlines()],'return {Version="17.0.0",']
for name,values in [('Skip',skip),('Separators',separators),('Marks',marks)]:
    lines.append(name+'={');lines.extend('{%d,%d},'%tuple(v)for v in values);lines.append('},')
lines.append('}\n')
(ROOT/'src/HTMLEngine/Layout/TextEmphasisData.luau').write_text('\n'.join(lines),encoding='utf8')
print('Unicode17 emphasis:',len(skip),'skip intervals;',len(separators),'separator;',len(marks),'mark intervals')
