"""Generate the complete pinned UCD normalization and UTS #46 host tables.

Run with --download to refresh cached primary source files. Runtime modules use
only these generated tables; they never fetch data or depend on host Unicode.
"""
from pathlib import Path
import argparse
import hashlib
import json
import urllib.request

ROOT = Path(__file__).resolve().parent.parent
VERSION = "17.0.0"
CACHE = ROOT / "scripts/data/unicode-17.0.0"
SOURCES = {
    "UnicodeData.txt": "ucd/UnicodeData.txt",
    "DerivedNormalizationProps.txt": "ucd/DerivedNormalizationProps.txt",
    "NormalizationTest.txt": "ucd/NormalizationTest.txt",
    "IdnaMappingTable.txt": "idna/IdnaMappingTable.txt",
    "DerivedBidiClass.txt": "ucd/extracted/DerivedBidiClass.txt",
    "DerivedJoiningType.txt": "ucd/extracted/DerivedJoiningType.txt",
}

def rows(path):
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if line and not line.startswith("@"):
            yield [part.strip() for part in line.split(";")]

def span(source):
    parts = source.split("..")
    return int(parts[0], 16), int(parts[-1], 16)

def array(values):
    return "{" + ",".join(str(value) for value in values) + "}"

def generate(download=False):
    CACHE.mkdir(parents=True, exist_ok=True)
    hashes = {}
    license_path = CACHE.parent / "UNICODE-LICENSE.txt"
    if download or not license_path.exists():
        license_path.write_bytes(urllib.request.urlopen("https://www.unicode.org/license.txt", timeout=30).read())
    hashes["UnicodeLicense"] = hashlib.sha256(license_path.read_bytes()).hexdigest()
    for name, suffix in SOURCES.items():
        target = CACHE / name
        if download or not target.exists():
            target.write_bytes(urllib.request.urlopen("https://www.unicode.org/Public/" + VERSION + "/" + suffix, timeout=60).read())
        hashes[name] = hashlib.sha256(target.read_bytes()).hexdigest()
    excluded = set()
    for row in rows(CACHE / "DerivedNormalizationProps.txt"):
        if row[1] == "Full_Composition_Exclusion":
            low, high = span(row[0]); excluded.update(range(low, high + 1))
    decompositions, classes, compositions, marks = {}, {}, {}, []
    for row in rows(CACHE / "UnicodeData.txt"):
        code, combining, mapping = int(row[0], 16), int(row[3]), row[5]
        if row[2].startswith('M'): marks.append(code)
        if combining: classes[code] = combining
        if mapping:
            parts = mapping.split(); compatibility = parts[0].startswith("<")
            if compatibility: parts.pop(0)
            values = [int(part, 16) for part in parts]
            decompositions[code] = [1 if compatibility else 0] + values
            if not compatibility and len(values) == 2 and code not in excluded:
                compositions.setdefault(values[0], {})[values[1]] = code
    folder = ROOT / "src/HTMLEngine/JavaScript"
    lines = ["--!strict", "-- Generated by scripts/generate-unicode-text-data.py; Unicode 17.0.0.",
             "-- Unicode data license: https://www.unicode.org/license.txt", "return {Version=\"17.0.0\", Decomposition={"]
    lines += [f"[{code}]={array(value)}," for code, value in decompositions.items()]
    lines += ["}, Combining={"] + [f"[{code}]={value}," for code, value in classes.items()]
    lines += ["}, Composition={"]
    lines += [f"[{first}]={{{','.join(f'[{second}]={code}' for second,code in rest.items())}}}," for first, rest in compositions.items()]
    lines += ["}, Marks={"] + [f"[{code}]=true," for code in marks] + ["}}", ""]
    (folder / "UnicodeNormalizationData.luau").write_text("\n".join(lines), encoding="utf-8")
    lines = ["--!strict", "-- Generated Unicode 17.0.0 UTS #46 nontransitional mapping and validation data.",
             "-- Unicode data license: https://www.unicode.org/license.txt", "return {Version=\"17.0.0\", Mapping={"]
    for row in rows(CACHE / "IdnaMappingTable.txt"):
        low, high = span(row[0]); mapping = [int(part, 16) for part in (row[2] if len(row) > 2 else "").split()]
        lines.append("{" + f"{low},{high},\"{row[1]}\",{array(mapping)}" + "},")
    for name, filename in [("Bidi", "DerivedBidiClass.txt"), ("Joining", "DerivedJoiningType.txt")]:
        entries = []
        for row in rows(CACHE / filename):
            low, high = span(row[0]); entries.append((low, high, row[1]))
        lines.append("}," + name + "={")
        lines += [f'{{{low},{high},"{value}"}},' for low, high, value in sorted(entries)]
    lines += ["}}", ""]
    (folder / "LibraryURLIDNAData.luau").write_text("\n".join(lines), encoding="utf-8")
    (CACHE / "manifest.json").write_text(json.dumps({"version": VERSION, "baseURL": "https://www.unicode.org/Public/17.0.0/", "sha256": hashes}, indent=2) + "\n", encoding="utf-8")
    # Keep the primary test corpus as text so the Luau test harness can stream
    # cases without generating tens of thousands of source-code constants.
    (ROOT / "tests/fixtures/unicode-normalization-17.txt").write_bytes((CACHE / "NormalizationTest.txt").read_bytes())
    print(f"Unicode {VERSION}: {len(decompositions)} decompositions, {len(classes)} combining classes, {sum(map(len,compositions.values()))} compositions")

if __name__ == "__main__":
    parser = argparse.ArgumentParser(); parser.add_argument("--download", action="store_true")
    generate(parser.parse_args().download)
