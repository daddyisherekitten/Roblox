// Deterministic offline original-image pack. No asset uploads or network access.
const fs = require('node:fs');
const path = require('node:path');
const zlib = require('node:zlib');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const hash = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const quote = value => JSON.stringify(value);
function pack(decodedDirectory, outputDirectory = path.join(root, 'src/HTMLEngine/Websites/Assets'), options = {}) {
  const decoded = JSON.parse(fs.readFileSync(path.join(decodedDirectory, 'decoded.json'), 'utf8'));
  assert.ok(Array.isArray(decoded), 'Decoded image manifest must be an array');
  assert.equal(new Set(decoded.map(image => image.Path)).size, decoded.length, 'Original image paths must be unique');
  fs.mkdirSync(path.join(outputDirectory, 'Pixels'), {recursive:true});
  const templates = path.join(__dirname, 'data/wttg2-image-runtime');
  for (const name of ['ImageCatalog.luau', 'PixelDecoder.luau']) {
    fs.copyFileSync(path.join(templates, name), path.join(outputDirectory, name));
  }
  const records = [];
  const storedTiles = new Map();
  let packedBytes = 0, rawBytes = 0, storedRawBytes = 0;
  for (const [index, image] of decoded.entries()) {
    const rgba = fs.readFileSync(path.join(decodedDirectory, image.File));
    assert.ok(Number.isSafeInteger(image.Width) && image.Width > 0 && Number.isSafeInteger(image.Height) && image.Height > 0, 'Invalid original image dimensions');
    assert.equal(rgba.length, image.Width * image.Height * 4);
    if (image.RGBASHA256) assert.equal(hash(rgba), image.RGBASHA256, 'Decoded image changed before packing');
    const tiles = [];
    for (let y = 0; y < image.Height; y += 1022) for (let x = 0; x < image.Width; x += 1022) {
      const coreW = Math.min(1022,image.Width-x), coreH = Math.min(1022,image.Height-y);
      // A one-pixel sampling border prevents bilinear seams at tile boundaries.
      const left = Math.max(0,x-1), top = Math.max(0,y-1);
      const width = Math.min(image.Width,x+coreW+1)-left, height = Math.min(image.Height,y+coreH+1)-top;
      const pixels = Buffer.alloc(width*height*4);
      for(let row=0;row<height;row++) rgba.copy(pixels,row*width*4,((top+row)*image.Width+left)*4,((top+row)*image.Width+left+width)*4);
      const sha256 = hash(pixels), key = `${width}x${height}:${sha256}`;
      let stored = storedTiles.get(key);
      if (!stored) {
        const compressed = zlib.zstdCompressSync(pixels,{params:{[zlib.constants.ZSTD_c_compressionLevel]:10,[zlib.constants.ZSTD_c_contentSizeFlag]:1}});
        assert.deepEqual(zlib.zstdDecompressSync(compressed),pixels,'Lossless Zstd roundtrip');
        const name = `Image${String(index).padStart(3,'0')}Tile${tiles.length}`;
        const chunks = compressed.toString('base64').match(/.{1,60000}/g) || [''];
        const luau = `--!strict\n-- Original RGBA image tile; decoded lazily by ImageCatalog.\nreturn {Width=${width},Height=${height},Bytes=${pixels.length},Data={\n${chunks.map(x=>'\t'+quote(x)+',').join('\n')}\n}}\n`;
        fs.writeFileSync(path.join(outputDirectory,'Pixels',name+'.luau'),luau);
        packedBytes+=compressed.length; storedRawBytes+=pixels.length;
        stored = {name, compressedBytes:compressed.length};
        storedTiles.set(key, stored);
      }
      rawBytes+=pixels.length;
      tiles.push({...stored,x,y,coreW,coreH,left,top,width,height,sha256});
    }
    records.push({path:image.Path,width:image.Width,height:image.Height,frames:image.Frames,frameSelection:image.FrameSelection??0,sourceSHA256:image.SourceSHA256,rgbaSHA256:hash(rgba),tiles});
  }
  const manifest = `--!strict\n-- Generated by scripts/pack-wttg2-images.cjs; original dimensions are retained.\nreturn {\n${records.map(image=>`\t{Path=${quote(image.path)},Width=${image.width},Height=${image.height},Frames=${image.frames},Tiles={${image.tiles.map(t=>`{Name=${quote(t.name)},X=${t.x},Y=${t.y},Width=${t.coreW},Height=${t.coreH},Left=${t.left},Top=${t.top},PixelWidth=${t.width},PixelHeight=${t.height}}`).join(',')}}},`).join('\n')}\n}\n`;
  fs.writeFileSync(path.join(outputDirectory,'ImageManifest.luau'),manifest);
  const proof = {date:'2026-10-19',images:records.length,tiles:records.reduce((n,x)=>n+x.tiles.length,0),uniqueTiles:storedTiles.size,rawBytes,storedRawBytes,packedBytes,losslessZstdRoundtrips:true,animatedImages:records.filter(x=>x.frames>1).map(({path,frames})=>({path,frames})),records};
  const proofPath = options.proofPath || path.join(root,'build/wiki1-port-20261019/image-pack.json');
  fs.mkdirSync(path.dirname(proofPath), {recursive:true});
  fs.writeFileSync(proofPath,JSON.stringify(proof,null,2)+'\n');
  return proof;
}
