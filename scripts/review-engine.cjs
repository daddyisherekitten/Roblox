// Structural inventory for every first-party engine module. This is not a
// semantic review or proof of behavior; callers and test links are lexical.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto'),cp=require('node:child_process'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..'),engine=path.join(root,'src/HTMLEngine');
const relative=file=>path.relative(root,file).replaceAll('\\','/');
function files(dir){return fs.readdirSync(dir,{withFileTypes:true}).flatMap(e=>e.isDirectory()?files(path.join(dir,e.name)):[path.join(dir,e.name)]);}
const sources=files(engine).filter(f=>f.endsWith('.luau')).sort();
const records=sources.map(file=>{
 const source=fs.readFileSync(file,'utf8'),dependencies=[],unresolved=[];
 for(const match of source.matchAll(/require\s*\(\s*script((?:\.[A-Za-z_][A-Za-z_0-9]*)+)\s*\)/g)){
  let base=file.endsWith('/init.luau')||file.endsWith('\\init.luau')?path.dirname(file):file.slice(0,-5);
  for(const part of match[1].slice(1).split('.'))base=part==='Parent'?path.dirname(base):path.join(base,part);
  const target=fs.existsSync(base+'.luau')?base+'.luau':path.join(base,'init.luau');
  if(fs.existsSync(target))dependencies.push(relative(target));else unresolved.push(relative(target));
 }
 const functions=[...source.matchAll(/(?:local\s+)?function\s+([A-Za-z_][\w.:]*)\s*\(/g)].map(m=>({name:m[1],line:source.slice(0,m.index).split('\n').length}));
 return {path:relative(file),sha256:crypto.createHash('sha256').update(source).digest('hex'),lines:source.split('\n').length,
  generated:/Generated by|generated from|Generated from|DO NOT EDIT|Unicode .*data|font-outline data/i.test(source.slice(0,1800)),
  dependencies:[...new Set(dependencies)].sort(),unresolved,callers:[],functions,
  markers:{checkpoints:(source.match(/(?:WorkContext\.checkpoint|:checkpoint|checkAlive|alive\(\))/g)||[]).length,
   tableClones:(source.match(/table\.clone\s*\(/g)||[]).length,
   renderSignals:(source.match(/RenderStepped|Heartbeat|PreRender|BindToRenderStep/g)||[]).length,
   asynchronous:(source.match(/task\.(?:spawn|defer|delay)|:Connect\s*\(/g)||[]).length},
  inspection:'Structural scan of complete file; markers alone prove no optimization opportunity'};
});
const byPath=new Map(records.map(r=>[r.path,r]));
for(const r of records)for(const d of r.dependencies)byPath.get(d)?.callers.push(r.path);
const cycles=[],active=[],seen=new Set();
function visit(key){const at=active.indexOf(key);if(at>=0){cycles.push([...active.slice(at),key]);return}if(seen.has(key))return;seen.add(key);active.push(key);for(const d of byPath.get(key)?.dependencies||[])visit(d);active.pop();}
for(const r of records)visit(r.path);
const report={schema:'engine-structural-review/v1',date:'2026-10-06',scope:'All first-party src/HTMLEngine Luau files; lexical static dependencies/named function declarations, not a dynamic call graph or full semantic/native verification',cycles,records};
const encoded=JSON.stringify(report,null,2)+'\n';
fs.mkdirSync(path.join(root,'build'),{recursive:true});
const out=path.join(root,'build/engine-review-map.json');
fs.writeFileSync(out,encoded);
const snapshot=path.join(root,'docs/audit-2026-10-06/engine-map.json');
if(process.argv.includes('--snapshot')){fs.mkdirSync(path.dirname(snapshot),{recursive:true});fs.writeFileSync(snapshot,encoded)}
if(process.argv.includes('--check'))assert.equal(fs.readFileSync(snapshot,'utf8'),encoded,'Engine review snapshot differs from the current code; this is a dated review, not an automatic claim about new code');
console.log(`Engine structure: ${records.length} files, ${records.reduce((n,r)=>n+r.functions.length,0)} named functions, ${records.reduce((n,r)=>n+r.dependencies.length,0)} static dependency edges, ${cycles.length} cycles, ${records.reduce((n,r)=>n+r.unresolved.length,0)} unresolved static paths.`);
if(process.argv.includes('--lint')){
 const analyzer=path.join(root,'build/tools/luau/luau-analyze.exe'),results=[];
 for(let index=0;index<sources.length;index+=15){
  const run=cp.spawnSync(analyzer,['--formatter=plain',...sources.slice(index,index+15)],{encoding:'utf8',maxBuffer:32*1024*1024,timeout:60000});
  const output=(run.stdout||'')+(run.stderr||'');
  for(const line of output.split(/\r?\n/))if(/:\s*\(W\d+\)\s*(?!TypeError:)[A-Za-z]+:/.test(line))results.push(line.replaceAll(root,'<root>').replaceAll(root.replaceAll('\\','/'),'<root>'));
  if(run.error)results.push(`Analyzer batch ${index}: ${run.error.message}`);
 }
 fs.writeFileSync(path.join(root,'build/engine-review-lint.txt'),results.join('\n')+'\n');
 console.log(`Engine lexical lint: ${results.length} non-type diagnostics; Roblox-aware type checking is a separate scope.`);
}
