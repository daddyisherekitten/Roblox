'use strict';

// Publish reviewed original pages from the user's local game installation.
// The game archive is opened read-only; all output stays inside the project.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const ORIGIN = 'http://localhost:8000';
const sha256 = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const quote = value => '"' + String(value).replace(/["\\\x00-\x1f\x7f]/g, c => c === '"' || c === '\\' ? '\\' + c : '\\' + c.charCodeAt(0).toString().padStart(3, '0')) + '"';
function longString(source) {
  let equals = '==';
  while (source.includes(']' + equals + ']')) equals += '=';
  return '[' + equals + '[\n' + source + ']' + equals + ']';
}
function inside(parent, relative) {
  const target = path.resolve(parent, relative);
  if (target === parent || !target.startsWith(parent + path.sep)) throw Error('Output escaped its directory: ' + relative);
  return target;
}
function validMember(member) {
  if (typeof member !== 'string' || !member.startsWith('/') || member.includes('\\') || member.split('/').includes('..')) throw Error('Unsafe archive member: ' + member);
  return member;
}
function sourceModule(source, original) {
  return '--!strict\n-- Generated by scripts/wttg2-site-publisher.cjs from ' + original + '.\nreturn ' + longString(source) + '\n';
}
function sourceURL(reference, current) {
  if (/^(?:data|javascript|mailto|tel):/i.test(reference) || reference.startsWith('#')) return null;
  try { const url = new URL(reference, ORIGIN + current); return url.origin === ORIGIN ? decodeURI(url.pathname) : null; } catch { return null; }
}
function references(source, current) {
  const found = new Set();
  const patterns = [/(?:src|href|poster)\s*=\s*["']([^"']+)["']/gi, /url\(\s*["']?([^"')\s]+)["']?\s*\)/gi, /@import\s+["']([^"']+)["']/gi];
  for (const pattern of patterns) for (const match of source.matchAll(pattern)) { const member = sourceURL(match[1], current); if (member) found.add(member); }
  return found;
}
function domain(name) {
  return name.toLowerCase().replace(/[^a-z0-9]/g, '-') + '.ann';
}
function injectHead(html) {
  const host = '\n<style data-wttg2-cursor>[onmouseover*="LinkHover"] { cursor: pointer; }</style>\n<script src="/wttg2-config.js"></script>\n<script src="/wttg2-host-bridge.js"></script>\n';
  if (!/<head\b[^>]*>/i.test(html)) throw Error('Original HTML has no head');
  return html.replace(/<head\b[^>]*>/i, head => head + host).replace(/<script\b[^>]*\bsrc\s*=\s*["'][^"']*jQuery\.min\.js["'][^>]*>\s*<\/script\s*>/ig, tag => tag + '\n<script>WTTG2Host.installJQuery();</script>');
}

function placeholderHTML(reason) {
  const text=String(reason||'This archived page is unavailable in this port.').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
  return '<!doctype html><html><head><meta charset="utf-8"><title>Page unavailable</title><style>body{background:#111;color:#aaa;font:16px Arial,sans-serif;max-width:680px;margin:64px auto;padding:24px}h1{font-size:24px;color:#ddd}a{color:#99b1b9}</style></head><body><h1>Page unavailable</h1><p>'+text+'</p><p><a href="/wiki1/index.html">The Deep Wiki</a></p></body></html>';
}

function publish({ workspace, registry, archivePath, selectedPath, readEntry, imageSourcesModulePath, browserRoot, modulesRoot, buildRoot, catalogPath } = {}) {
  workspace = path.resolve(workspace || path.join(__dirname, '..'));
  const selected = typeof selectedPath === 'object' ? selectedPath : JSON.parse(fs.readFileSync(selectedPath || path.join(workspace, 'build/wiki1-port-20261019/research/selected-wiki1.json'), 'utf8'));
  registry = typeof registry === 'string' ? JSON.parse(fs.readFileSync(registry, 'utf8')) : registry;
  if (!Array.isArray(registry)) throw Error('registry must be an array of original archive entries');
  if (!Array.isArray(selected.sites) || !Array.isArray(selected.deadLinks)) throw Error('Selection needs sites and deadLinks');
  const full=Array.isArray(selected.documents);
  if(full && selected.resourcePolicy?.status!=='reviewed')throw Error('Full publication requires a reviewed resource policy');
  const entries = new Map(registry.map(r => [validMember(r.Path ?? r.path), { Path: r.Path ?? r.path, Offset: r.Offset ?? r.offset, Length: r.Length ?? r.length }]));
  const canonical=new Map([...entries.keys()].map(p=>[p.toLowerCase(),p]));
  const fd = readEntry ? null : fs.openSync(archivePath, 'r');
  const original = new Map();
  function read(member) {
    if (original.has(member)) return original.get(member);
    const entry = entries.get(member); if (!entry) throw Error('Original archive member missing: ' + member);
    const bytes = readEntry ? Buffer.from(readEntry(entry)) : Buffer.alloc(entry.Length);
    if (!readEntry && fs.readSync(fd, bytes, 0, bytes.length, entry.Offset) !== bytes.length) throw Error('Truncated archive entry: ' + member);
    if (bytes.length !== entry.Length) throw Error('Entry length differs: ' + member);
    original.set(member, bytes); return bytes;
  }
  function scriptSource(member){
    let source=read(member).toString('utf8');
    if(member==='/thethree/puzzle.js'){
      const needle=`+ pick + '"')`,fixed=`+ pick + '"]')`;
      if(source.split(needle).length!==2)throw Error('Original TheThree selector no longer matches the reviewed repair');
      source=source.replace(needle,fixed);
    }
    return source;
  }
  try {
    const wikis=selected.wikis||[{index:1,path:'/wiki1/index.html',module:'DeepWiki',siteNames:selected.sites.map(s=>s.m_Name),deadNames:selected.deadLinks.map(s=>s.m_Name)}];
    const documents=full?selected.documents:[{logicalPath:'wiki1/index.html'},...selected.sites.flatMap(s=>s.Pages)];
    const pagePath=d=>validMember(d.archivePath||d.path||'/'+d.logicalPath);
    const documentByPath=new Map(documents.map(d=>[pagePath(d),d]));
    const isWithheld=d=>Boolean(d&&(String(d.status).startsWith('withheld')||d.status==='placeholder'||d.withheldReason));
    const prefixes = [...wikis.map(w=>w.path.split('/')[1]), ...selected.sites.map(s => s.DocumentRoot)];
    const allowedRoots=new Set(selected.resourcePolicy?.allowedRoots||prefixes);
    const excludedRoots=new Set(selected.resourcePolicy?.excludedRoots||[]);
    const allowedShared=new Set(selected.resourcePolicy?.allowedSharedPaths||['/jQuery.min.js','/basic.js']);
    const allowedPaths=selected.resourcePolicy?.allowedPaths&&new Set(selected.resourcePolicy.allowedPaths);
    const excludedPaths=new Set(selected.resourcePolicy?.excludedPaths||[]);
    const allowedResource=p=>!p.endsWith('/.DS_Store')&&p!=='/.DS_Store'&&!excludedPaths.has(p)&&(allowedPaths?allowedPaths.has(p):allowedShared.has(p)||(!excludedRoots.has(p.split('/')[1])&&allowedRoots.has(p.split('/')[1])));
    const wanted = new Set(['/jQuery.min.js', '/basic.js']);
    for (const member of entries.keys()) if (allowedResource(member)) wanted.add(member);
    for(const member of documentByPath.keys())wanted.add(member);
    // Follow referenced shared resources, without downloading external addresses.
    const queue = [...wanted];
    for (let i = 0; i < queue.length; i++) {
      const member = queue[i]; if (!entries.has(member)) throw Error('Selected source absent: ' + member);
      if (!/\.(?:html?|css)$/i.test(member)||isWithheld(documentByPath.get(member))) continue;
      for (const requested of references(read(member).toString('utf8'), member)) {
        const dependency=canonical.get(requested.toLowerCase())||requested;
        if (!entries.has(dependency) || wanted.has(dependency)) continue;
        // Cross-site links are navigation targets, not implicit catalog additions.
        if (/\.html?$/i.test(dependency) && !documentByPath.has(dependency)) continue;
        if(!allowedResource(dependency))continue;
        wanted.add(dependency); queue.push(dependency);
      }
    }
    browserRoot = path.resolve(browserRoot||path.join(workspace, 'examples/websites'));
    modulesRoot = path.resolve(modulesRoot||path.join(workspace, 'src/HTMLEngine/Websites'));
    buildRoot = path.resolve(buildRoot||path.join(workspace, full?'build/wttg2-full-20261019':'build/wiki1-port-20261019'));
    catalogPath=path.resolve(catalogPath||path.join(workspace,'scripts/data',full?'wttg2-full-catalog.json':'wttg2-catalog.json'));
    const bridgePath = path.resolve(workspace, 'scripts/wttg2-host-bridge.js');
    const compatPath = path.resolve(workspace, 'scripts/wttg2-jquery-compat.js');
    const bridge = fs.readFileSync(bridgePath, 'utf8');
    const compatibility = fs.readFileSync(compatPath, 'utf8');
    const pagePaths = documents.map(pagePath);
    if (new Set(pagePaths.map(p=>p.toLowerCase())).size !== pagePaths.length) throw Error('Duplicate HTML routes');
    const unavailablePath=pagePaths.find(p=>p.toLowerCase()==='/notfound/index.html')||'/unavailable/index.html';
    const sites = selected.sites.map(s => ({ name:s.m_Name,host: domain(s.m_Name), path: '/' + s.Pages[0].logicalPath, title: s.PageTitle, description: s.PageDesc, dead: false }));
    const dead = selected.deadLinks.map(s => ({ name:s.m_Name,host: domain(s.m_Name), path: unavailablePath, title: s.PageTitle, description: s.PageDesc, dead: true }));
    const wikiSites=full?wikis.map(w=>({name:w.m_Name,host:domain(w.m_Name),path:w.path,title:w.PageTitle,description:w.PageDesc==='N/A'?'The Deep Wiki directory':w.PageDesc,dead:false,directory:true})):[];
    const listedSites = [...sites, ...dead,...wikiSites].sort((a, b) => a.title.localeCompare(b.title, 'en', { sensitivity: 'variant' }));
    const wikiConfiguration=wikis.map(w=>{
      const names=new Set([...(w.displaySiteNames||w.siteNames||[]),...(w.displayDeadNames||w.deadNames||[]),...(w.crossWikiNames||[])]);
      return{index:w.index,path:w.path,title:w.PageTitle||'The Deep Wiki '+w.index,siteNames:listedSites.filter(s=>names.has(s.name)).map(s=>s.name)};
    });
    const allPagePaths=[...new Set([...pagePaths,unavailablePath])];
    const configuration = 'window.WTTG2_PORT = ' + JSON.stringify({pages:allPagePaths,pageMap:Object.fromEntries(allPagePaths.map(p=>[p.toLowerCase(),p])),aliasIndex:Object.fromEntries(listedSites.map((s,i)=>[s.host.toLowerCase(),i])),siteIndex:Object.fromEntries(listedSites.map((s,i)=>[s.name,i])), sites: listedSites,wikis:wikiConfiguration, unavailablePath,puzzleWikiPath:'/wiki3/index.html' }) + ';\n';
    const generated = new Map([['/wttg2-config.js', Buffer.from(configuration)], ['/wttg2-host-bridge.js', Buffer.from(bridge)]]);
    const files = [];
    const missingReferences=[],excludedReferences=[],externalReferences=[];
    const observedReferences=new Set();
    function auditReferences(source,current){
      for(const requested of references(source,current)){
        const resolved=canonical.get(requested.toLowerCase())||requested;
        const key=current+'|'+resolved;if(observedReferences.has(key))continue;observedReferences.add(key);
        if(!entries.has(resolved)&&!generated.has(resolved))missingReferences.push({sourcePath:current,resolvedPath:resolved});
        else if(!wanted.has(resolved)&&!generated.has(resolved))excludedReferences.push({sourcePath:current,resolvedPath:resolved});
      }
      for(const match of source.matchAll(/(?:src|href|poster)\s*=\s*["'](https?:\/\/[^"']+)["']/gi))if(!match[1].startsWith(ORIGIN+'/'))externalReferences.push({sourcePath:current,url:match[1]});
    }
    function writeBrowser(member, bytes, metadata = {}) {
      const target = inside(browserRoot, member.slice(1)); fs.mkdirSync(path.dirname(target), { recursive: true }); fs.writeFileSync(target, bytes);
      files.push({ path: member, target: path.relative(workspace, target).replaceAll('\\', '/'), byteLength: bytes.length, sha256: sha256(bytes), ...metadata });
    }
    for (const member of [...wanted].sort()) {
      const source = read(member),document=documentByPath.get(member),withheld=isWithheld(document);
      const output = /\.html?$/i.test(member) ? Buffer.from(injectHead(withheld?placeholderHTML('The original content of this archived page is unavailable in this port.'):source.toString('utf8'))) : member==='/thethree/puzzle.js'?Buffer.from(scriptSource(member)):source;
      if(/\.(?:html?|css)$/i.test(member))auditReferences(output.toString('utf8'),member);
      writeBrowser(member, output, { originalArchivePath: member, originalSHA256: sha256(source), originalLength: source.length,status:withheld?'withheld':'original',...(withheld?{withheldReason:document.withheldReason}:{}), transform: withheld?'unavailable-placeholder':member==='/thethree/puzzle.js'?'repair-original-missing-selector-closing-bracket':output.equals(source) ? 'none' : 'inject-cursor-css-config-host-bridge-and-offline-service-adapter' });
    }
    for (const [member, bytes] of generated) writeBrowser(member, bytes, { transform: 'port-host-integration' });
    const sourceByURL = new Map();
    for (const [member, bytes] of generated) sourceByURL.set(ORIGIN + member, bytes.toString('utf8'));
    const dependenciesByURL=new Map();
    const catalogRequire = imageSourcesModulePath || 'script.Parent.Assets.ImageCatalog';
    const modules = [];
    for (const sourcePath of pagePaths) {
      const site = selected.sites.find(s => sourcePath.startsWith('/' + s.DocumentRoot + '/'));
      const wiki=wikis.find(w=>w.path===sourcePath),document=documentByPath.get(sourcePath),withheld=isWithheld(document);
      const home = site && '/' + site.Pages[0].logicalPath === sourcePath;
      const filename = path.posix.basename(sourcePath, '.html');
      const name = site ? (home ? site.m_Name : site.m_Name + '_' + filename.replace(/[^A-Za-z0-9_]/g, '_')) : wiki?wiki.module||('DeepWiki'+(wiki.index===1?'':wiki.index)):'Archive_'+sourcePath.slice(1).replace(/\.html?$/i,'').replace(/[^A-Za-z0-9_]/g,'_');
      if (!/^[A-Za-z][A-Za-z0-9_]*$/.test(name)) throw Error('Invalid generated module name ' + name);
      const moduleRoot = inside(modulesRoot, name); fs.mkdirSync(moduleRoot, { recursive: true });
      const html = injectHead(withheld?placeholderHTML('The original content of this archived page is unavailable in this port.'):read(sourcePath).toString('utf8'));
      const styleSources=new Set(),scriptSources=new Set([...generated.keys()]);
      for(const match of html.matchAll(/<script\b[^>]*\bsrc\s*=\s*["']([^"']+)["'][^>]*>/gi)){
        const requested=sourceURL(match[1],sourcePath),dependency=canonical.get(requested?.toLowerCase())||requested;
        if(dependency&&(wanted.has(dependency)||generated.has(dependency)))scriptSources.add(dependency);
      }
      const styleQueue=[...references(html,sourcePath)].map(p=>canonical.get(p.toLowerCase())||p).filter(p=>/\.css$/i.test(p)&&wanted.has(p));
      for(let i=0;i<styleQueue.length;i++){
        const current=styleQueue[i];if(styleSources.has(current))continue;styleSources.add(current);
        for(const requested of references(read(current).toString('utf8'),current)){const dependency=canonical.get(requested.toLowerCase())||requested;if(/\.css$/i.test(dependency)&&wanted.has(dependency)&&!styleSources.has(dependency))styleQueue.push(dependency);}
      }
      for(const scriptPath of scriptSources)if(!sourceByURL.has(ORIGIN+scriptPath))sourceByURL.set(ORIGIN+scriptPath,scriptPath.toLowerCase()==='/jquery.min.js'?compatibility:scriptSource(scriptPath));
      dependenciesByURL.set(ORIGIN+sourcePath,[...scriptSources].map(p=>ORIGIN+p));
      const ownStylesheet = '/' + path.posix.dirname(sourcePath).slice(1) + '/style.css';
      const css = styleSources.has(ownStylesheet) ? read(ownStylesheet).toString('utf8') : '';
      const images=new Set();
      for(const[current,source]of [[sourcePath,html],...[...styleSources].map(p=>[p,read(p).toString('utf8')])])for(const requested of references(source,current)){
        const dependency=canonical.get(requested.toLowerCase())||requested;
        if(/\.(?:png|jpe?g|gif)$/i.test(dependency)&&wanted.has(dependency))images.add(dependency);
      }
      const url = ORIGIN + sourcePath;
      const titleMatch = html.match(/<title\b[^>]*>([\s\S]*?)<\/title>/i);
      const title = titleMatch ? titleMatch[1].replace(/<[^>]*>/g, '').trim() : site?.PageTitle || 'The Deep Wiki';
      const lines = ['--!strict', '-- Generated by scripts/wttg2-site-publisher.cjs. Content source: ' + sourcePath, 'local ImageCatalog = require(' + catalogRequire + ')','local HostScripts = require(script.Parent.Assets.HostScripts)', 'return {', '\tName = ' + quote(title) + ',', '\tURL = ' + quote(url) + ',', '\tPath = ' + quote(sourcePath) + ',', '\tCatalogHidden = ' + String(Boolean(!wiki&&(!site||!home))) + ',', '\tHTML = require(script.HTML),', '\tStylesheets = {'];
      for (const stylePath of styleSources) {
        const value = stylePath === ownStylesheet ? 'require(script.CSS)' : longString(read(stylePath).toString('utf8'));
        lines.push('\t\t[' + quote(ORIGIN + stylePath) + '] = ' + value + ',');
      }
      if (css) lines.push('\t\t["style.css"] = require(script.CSS),');
      lines.push('\t},', '\tOptions = {');
      if (wiki) lines.push('\t\tDefaultFont = "Arial",');
      lines.push('\t\tSVGs = ImageCatalog.forPage(' + quote(url) + ',{'+[...images].map(quote).join(',')+'}),', '\t\tJavaScriptServices = {', '\t\t\tScriptSources = {');
      lines.splice(lines.length-1,1,'\t\t\tScriptSources = HostScripts.forPage('+quote(url)+'),');
      lines.push('\t\t},', '\t},', '}', '');
      const sources = { 'init.luau': lines.join('\n'), 'HTML.luau': sourceModule(html, 'examples/websites' + sourcePath), 'CSS.luau': sourceModule(css, ownStylesheet) };
      const moduleFiles = [];
      for (const [filename, source] of Object.entries(sources)) {
        const target = inside(moduleRoot, filename); fs.writeFileSync(target, source); moduleFiles.push({ path: path.relative(workspace, target).replaceAll('\\', '/'), sha256: sha256(source), byteLength: Buffer.byteLength(source) });
      }
      modules.push({ name, url, sourcePath, title, siteName: site?.m_Name || wiki?.m_Name || null, CatalogHidden: Boolean(!wiki&&(!site||!home)),status:withheld?'withheld':'original',...(withheld?{withheldReason:document.withheldReason,withheldCode:document.withheldCode}:{}),dependencies:{styles:[...styleSources],scripts:[...scriptSources],images:[...images]}, files: moduleFiles });
    }
    const hostLines=['--!strict','-- Shared sources; documents receive only their actual script dependencies.','local sources = {'];
    for(const[url,source]of sourceByURL)hostLines.push('\t['+quote(url)+'] = '+longString(source)+',');
    hostLines.push('}','local dependencies = {');for(const[url,urls]of dependenciesByURL)hostLines.push('\t['+quote(url)+'] = {'+urls.map(quote).join(', ')+'},');
    hostLines.push('}','return { forPage = function(url: string): {[string]: string}','\tlocal result = {}','\tfor _, dependency in ipairs(dependencies[url] or {}) do result[dependency] = sources[dependency] end','\treturn result','end }','');
    const hostSource=hostLines.join('\n'),hostTarget=inside(modulesRoot,'Assets/HostScripts.luau');fs.mkdirSync(path.dirname(hostTarget),{recursive:true});fs.writeFileSync(hostTarget,hostSource);
    const supportFiles=[{path:path.relative(workspace,hostTarget).replaceAll('\\','/'),sha256:sha256(hostSource),byteLength:Buffer.byteLength(hostSource)}];
    const manifest = { date: '2026-10-19', publisher: 'scripts/wttg2-site-publisher.cjs', originalSource: archivePath, sourceReadOnly: true, origin: ORIGIN, selectedPath: typeof selectedPath === 'string' ? selectedPath : null, realCount: sites.length, deadLinkCount: dead.length, htmlCount: modules.length, Modules: modules, files, siteConfiguration: listedSites, sharedDependencies: [...wanted].filter(p => !prefixes.some(prefix => p.startsWith('/' + prefix + '/'))), compatibility: { browserJQuery: 'Original /jQuery.min.js', robloxJQuery: 'scripts/wttg2-jquery-compat.js', note: 'A limited jQuery API adapter preserves these original pages without running the full jQuery library inside the Roblox JavaScript VM.' }, differences: ['Stable .ann aliases are port configuration; the original game generates domains per save.', 'Page host bridge replaces the original Unity-native JS hooks.', 'Source image pixels are supplied by the separate ImageCatalog port.'] };
    manifest.supportFiles=supportFiles;manifest.wikis=wikiConfiguration;manifest.output={browserRoot,modulesRoot,catalogPath};manifest.MissingReferences=missingReferences;manifest.ExcludedReferences=excludedReferences;manifest.ExternalReferences=externalReferences;
    if(full)manifest.differences.push('All three Wiki templates display fixed disjoint rosters of 20 real and 10 fake sites plus the other two Wikis, covering all60 real sites. The original game chooses15 real and10 fake entries per Wiki in a randomized save.','Original confession services are answered offline and never submit visitor text.','TheThree puzzle.js has one missing selector closing bracket repaired; puzzle order and reset rules remain original.');
    fs.mkdirSync(buildRoot, { recursive: true }); fs.writeFileSync(inside(buildRoot, 'published-catalog.json'), JSON.stringify(manifest, null, 2) + '\n');
    const persistent = { date: manifest.date, publisher: manifest.publisher, origin: ORIGIN, selectedCounts: { realSites: sites.length, deadLinks: dead.length, htmlRoutes: modules.length }, Modules: modules, files, siteConfiguration: listedSites, compatibility: manifest.compatibility, imageCaveats: ['Browser previews use the unchanged original image files.', 'Roblox uses the separate ImageCatalog pixel/SVG bridge rather than published asset IDs.', 'Pixel dimensions, frame selection, and image resampling limits are documented by the image pack manifest; publication does not claim native Roblox visual parity.', 'DeepWiki declares Arial as its Roblox default font because its original CSS font stack is unavailable; the original CSS remains unchanged. Other sites have no publisher font override.'], differences: manifest.differences };
    persistent.supportFiles=supportFiles;persistent.wikis=wikiConfiguration;persistent.output=manifest.output;persistent.MissingReferences=missingReferences;persistent.ExcludedReferences=excludedReferences;persistent.ExternalReferences=externalReferences;
    fs.mkdirSync(path.dirname(catalogPath), { recursive: true }); fs.writeFileSync(catalogPath, JSON.stringify(persistent, null, 2) + '\n');
    return manifest;
  } finally { if (fd !== null) fs.closeSync(fd); }
}

